#!/usr/bin/env bash
# =============================================================================
# azimut-webapp — create/remove nginx vhosts for phpMyAdmin, phpPgAdmin and
# Roundcube.
#
#   azimut-webapp <phpmyadmin|phppgadmin|roundcube>
#   azimut-webapp remove <phpmyadmin|phppgadmin|roundcube>
#
# Vhost name: <app>.<PANEL_DOMAIN> (read from /etc/azimutcp/panel.env).
# =============================================================================
set -euo pipefail

ACTION="install"
if [ "${1:-}" = "remove" ]; then
    ACTION="remove"
    shift
fi
APP="${1:-}"

case "${APP}" in
    phpmyadmin|phppgadmin|roundcube) ;;
    *) echo "usage: azimut-webapp [remove] <phpmyadmin|phppgadmin|roundcube>" >&2; exit 2 ;;
esac

CONF="/etc/nginx/sites-available/azimut-${APP}.conf"
ENABLED="/etc/nginx/sites-enabled/azimut-${APP}.conf"

if [ "${ACTION}" = "remove" ]; then
    rm -f "${ENABLED}" "${CONF}"
    nginx -t >/dev/null 2>&1 && systemctl reload nginx >/dev/null 2>&1 || true
    echo "[azimut-webapp] removed ${APP} vhost"
    exit 0
fi

PANEL_DOMAIN="$(grep -h '^PANEL_DOMAIN=' /etc/azimutcp/panel.env 2>/dev/null | tail -1 | cut -d= -f2- || true)"
PANEL_DOMAIN="${PANEL_DOMAIN:-localhost}"

case "${APP}" in
    phpmyadmin) PORT=8081 ;;
    phppgadmin) PORT=8082 ;;
    roundcube)  PORT=8083 ;;
esac

if [[ "${PANEL_DOMAIN}" =~ ^[0-9.]+$ ]]; then
    LISTEN_LINE="listen ${PORT};"
    SERVER_NAME="_"
    URL="http://${PANEL_DOMAIN}:${PORT}/"
else
    LISTEN_LINE="listen 80;"
    SERVER_NAME="${APP}.${PANEL_DOMAIN}"
    URL="http://${APP}.${PANEL_DOMAIN}/"
fi

PHP_VERSION="$(ls -d /etc/php/*/fpm 2>/dev/null | sed -E 's#/etc/php/([0-9.]+)/fpm#\1#' | sort -V | tail -1)"
PHP_VERSION="${PHP_VERSION:-8.3}"
SOCK="/run/php/php${PHP_VERSION}-fpm.sock"

case "${APP}" in
    phpmyadmin) ROOT="/usr/share/phpmyadmin" ;;
    phppgadmin) ROOT="/usr/share/phppgadmin" ;;
    roundcube)
        if [ -d /usr/share/roundcube ]; then ROOT="/usr/share/roundcube";
        else ROOT="/var/lib/roundcube"; fi
        ;;
esac

if [ ! -d "${ROOT}" ]; then
    echo "document root not found for ${APP}: ${ROOT}" >&2
    exit 3
fi

cat > "${CONF}" <<EOF
# Generated by AzimutCP — ${APP} vhost
server {
    ${LISTEN_LINE}
    server_name ${SERVER_NAME};

    root ${ROOT};
    index index.php index.html;
    client_max_body_size 64m;

    access_log /var/log/nginx/${APP}.access.log;
    error_log  /var/log/nginx/${APP}.error.log;

    location / {
        try_files \$uri \$uri/ /index.php?\$args;
    }

    location ~ \.php\$ {
        include snippets/fastcgi-php.conf;
        fastcgi_pass unix:${SOCK};
    }

    location ~ /\.ht {
        deny all;
    }
}
EOF

ln -sf "${CONF}" "${ENABLED}"
if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx >/dev/null 2>&1 || true
    echo "[azimut-webapp] ${APP} available at ${URL}"
else
    rm -f "${ENABLED}"
    echo "nginx configuration test failed; vhost removed" >&2
    exit 4
fi
